#!/usr/bin/env python3
"""Write xmamba_luts.h: the exp/sigmoid/softplus tables of the Xmamba nonlinear
unit, taken from model/mamba_fixed.py so Python, C, Spike and RTL share them.
The tables belong to the ISA, not to a model.

Usage: gen_luts_h.py OUT.h
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "model"))
import mamba_fixed as mf  # noqa: E402


def arr(name, v):
    body = ",\n    ".join(", ".join(str(int(x)) for x in v[i:i + 6]) for i in range(0, len(v), 6))
    return f"static const int32_t {name}[{len(v)}] = {{\n    {body}\n}};"


def main(path):
    out = [
        "/* Generated by sim/spike/gen_luts_h.py from model/mamba_fixed.py. Do not edit. */",
        "#ifndef XMAMBA_LUTS_H", "#define XMAMBA_LUTS_H", "#include <stdint.h>",
        f"#define XM_EXP_SEGS  {mf.EXP_SEGS}", f"#define XM_SIG_SEGS  {mf.SIG_SEGS}",
        f"#define XM_SP_SEGS   {mf.SP_SEGS}", f"#define XM_SIG_RANGE {mf.SIG_RANGE}",
        f"#define XM_SP_RANGE  {mf.SP_RANGE}", f"#define XM_LOG2E_Q30 {mf.LOG2E_Q30}LL",
        f"#define XM_EXP_FB    {mf._seg_bits(1, mf.EXP_SEGS, 24)}",
        f"#define XM_SIG_FB    {mf._seg_bits(mf.SIG_RANGE, mf.SIG_SEGS, mf.QX)}",
        f"#define XM_SP_FB     {mf._seg_bits(mf.SP_RANGE, mf.SP_SEGS, mf.QX)}",
        "/* exp: 2^f, f in [0,1], Q29 */", arr("xm_exp2_q29", mf.T["exp2"]),
        "/* sigmoid(x), x in [0, XM_SIG_RANGE], Q30 */", arr("xm_sig_q30", mf.T["sig"]),
        "/* r(a) = log1p(e^-a) / e^-a, a in [0, XM_SP_RANGE], Q30 */", arr("xm_spr_q30", mf.T["spr"]),
        "#endif", ""]
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
