#!/usr/bin/env python3
"""
Generate a monolithic, self-contained cfu.v for CFU Playground.
Inlines xmamba_tables.vh into mb_xmamba_unit.v and concatenates
mb_mac_unit.v, mb_xmamba_unit.v, and cfu_top.v.
"""

from pathlib import Path
import sys

def generate_monolithic_cfu(pkg_root: Path, output_file: Path) -> Path:
    rtl_dir = pkg_root / "rtl"
    mac_file = rtl_dir / "mb_mac_unit.v"
    xmamba_file = rtl_dir / "mb_xmamba_unit.v"
    tables_file = rtl_dir / "xmamba_tables.vh"
    top_file = rtl_dir / "cfu_top.v"

    for f in (mac_file, xmamba_file, tables_file, top_file):
        if not f.exists():
            raise FileNotFoundError(f"Required source file not found: {f}")

    mac_content = mac_file.read_text(encoding="utf-8")
    tables_content = tables_file.read_text(encoding="utf-8")
    xmamba_content = xmamba_file.read_text(encoding="utf-8")
    top_content = top_file.read_text(encoding="utf-8")

    # Inline tables
    include_str = '`include "xmamba_tables.vh"'
    if include_str in xmamba_content:
        inlined_xmamba = xmamba_content.replace(
            include_str,
            f"// --- BEGIN INLINED xmamba_tables.vh ---\n{tables_content}\n// --- END INLINED xmamba_tables.vh ---"
        )
    else:
        inlined_xmamba = xmamba_content

    monolithic = f"""// ============================================================================
// Xmamba Monolithic CFU Top Module
// Autogenerated for CFU Playground (LiteX / VexRiscv / Renode / Vivado)
// Modules: mb_mac_unit, mb_xmamba_unit (with inlined tables), Cfu
// ============================================================================

`timescale 1ns / 1ps

// ============================================================================
// 1. MAC UNIT (mb_mac_unit.v)
// ============================================================================
{mac_content}

// ============================================================================
// 2. NONLINEAR & SCAN ENGINE (mb_xmamba_unit.v)
// ============================================================================
{inlined_xmamba}

// ============================================================================
// 3. CFU TOP ROUTING (cfu_top.v)
// ============================================================================
{top_content}
"""

    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(monolithic, encoding="utf-8")
    print(f"Generated monolithic CFU: {output_file} ({len(monolithic.splitlines())} lines)")
    return output_file

if __name__ == "__main__":
    script_dir = Path(__file__).resolve().parent
    pkg_root = script_dir.parent
    if len(sys.argv) > 1:
        out_path = Path(sys.argv[1]).resolve()
    else:
        out_path = pkg_root / "rtl" / "cfu.v"
    generate_monolithic_cfu(pkg_root, out_path)
