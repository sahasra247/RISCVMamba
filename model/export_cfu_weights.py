#!/usr/bin/env python3
"""
export_cfu_weights.py: Export Trained Weights to CFU SoC and Test Vectors (Member C task)
========================================================================================
1. Quantizes trained float32 weights from model/weights/*.npy into fixed-point integers
   matching the Xmamba Fixture struct layout.
2. Generates soc/trained_weights.h for compilation into the CFU C++ SoC and Verilator harnesses.
3. Generates test/test_vectors/ with binary and JSON files for 10 tokens across all layers/stages.
4. Generates results/reference_dump.json for compare.py verification.
"""

import json
import os
from pathlib import Path
import numpy as np

import mamba_step as ms


def quantize_int8(val, scale=64.0):
    q = np.round(val * scale).astype(int)
    return np.clip(q, -128, 127).astype(np.int8)


def quantize_int16(val, scale=256.0):
    q = np.round(val * scale).astype(int)
    return np.clip(q, -32768, 32767).astype(np.int16)


def export_cfu_header(weights_dir: Path, output_header: Path):
    weights = ms.load_weights(str(weights_dir))

    emb = quantize_int8(weights["backbone.embeddings.weight"], scale=24.0)
    head = quantize_int8(weights["lm_head.weight"], scale=64.0)
    norm_f = quantize_int16(weights["backbone.norm_f.weight"], scale=256.0)

    layers = []
    for i in range(2):
        prefix = f"backbone.layers.{i}."
        in_p = quantize_int8(weights[f"{prefix}mixer.in_proj.weight"], scale=64.0)
        conv = quantize_int8(weights[f"{prefix}mixer.conv1d.weight"][:, 0, :], scale=64.0)
        conv_b = quantize_int8(weights[f"{prefix}mixer.conv1d.bias"], scale=32.0)
        x_p = quantize_int8(weights[f"{prefix}mixer.x_proj.weight"], scale=64.0)
        dt_p = quantize_int8(weights[f"{prefix}mixer.dt_proj.weight"], scale=32.0)
        dt_b = quantize_int16(weights[f"{prefix}mixer.dt_proj.bias"], scale=256.0)
        out_p = quantize_int8(weights[f"{prefix}mixer.out_proj.weight"], scale=48.0)
        norm = quantize_int16(weights[f"{prefix}norm.weight"], scale=256.0)

        # Constants: channel * 4 + state -> A (decay), then channel + 32 -> D
        A = -np.exp(weights[f"{prefix}mixer.A_log"])
        D = weights[f"{prefix}mixer.D"]
        constants = np.zeros(40, dtype=np.int16)
        for ch in range(8):
            for st in range(4):
                constants[ch * 4 + st] = quantize_int16(A[ch, st], scale=256.0)
            constants[32 + ch] = quantize_int16(D[ch], scale=256.0)

        layers.append({
            "in_proj": in_p,
            "conv": conv,
            "conv_bias": conv_b,
            "x_proj": x_p,
            "dt_proj": dt_p,
            "dt_bias": dt_b,
            "out_proj": out_p,
            "norm": norm,
            "constants": constants
        })

    def format_arr(arr):
        flat = arr.flatten()
        return ", ".join(str(int(x)) for x in flat)

    lines = [
        "// Generated by export_cfu_weights.py (Member C task). Do not edit manually.",
        "#ifndef TRAINED_WEIGHTS_H",
        "#define TRAINED_WEIGHTS_H",
        "",
        "inline void load_trained_weights(Fixture& f) {",
    ]

    # Fill embedding
    lines.append(f"  static const int8_t kEmb[8][4] = {{{format_arr(emb)}}};")
    lines.append("  memcpy(f.embedding, kEmb, sizeof(f.embedding));")

    # Fill head
    lines.append(f"  static const int8_t kHead[8][4] = {{{format_arr(head)}}};")
    lines.append("  memcpy(f.head, kHead, sizeof(f.head));")

    # Fill final norm
    lines.append(f"  static const int16_t kNormF[4] = {{{format_arr(norm_f)}}};")
    lines.append("  memcpy(f.final_norm, kNormF, sizeof(f.final_norm));")

    # Fill layers
    for i in range(2):
        l = layers[i]
        lines.append(f"  // --- Layer {i} ---")
        lines.append(f"  static const int8_t kInProj_{i}[16][4] = {{{format_arr(l['in_proj'])}}};")
        lines.append(f"  memcpy(f.in_proj[{i}], kInProj_{i}, sizeof(f.in_proj[{i}]));")

        lines.append(f"  static const int8_t kConv_{i}[8][4] = {{{format_arr(l['conv'])}}};")
        lines.append(f"  memcpy(f.conv[{i}], kConv_{i}, sizeof(f.conv[{i}]));")

        lines.append(f"  static const int8_t kConvB_{i}[8] = {{{format_arr(l['conv_bias'])}}};")
        lines.append(f"  memcpy(f.conv_bias[{i}], kConvB_{i}, sizeof(f.conv_bias[{i}]));")

        lines.append(f"  static const int8_t kXProj_{i}[10][8] = {{{format_arr(l['x_proj'])}}};")
        lines.append(f"  memcpy(f.x_proj[{i}], kXProj_{i}, sizeof(f.x_proj[{i}]));")

        lines.append(f"  static const int8_t kDtProj_{i}[8][2] = {{{format_arr(l['dt_proj'])}}};")
        lines.append(f"  memcpy(f.dt_proj[{i}], kDtProj_{i}, sizeof(f.dt_proj[{i}]));")

        lines.append(f"  static const int16_t kDtB_{i}[8] = {{{format_arr(l['dt_bias'])}}};")
        lines.append(f"  memcpy(f.dt_bias[{i}], kDtB_{i}, sizeof(f.dt_bias[{i}]));")

        lines.append(f"  static const int8_t kOutP_{i}[4][8] = {{{format_arr(l['out_proj'])}}};")
        lines.append(f"  memcpy(f.out_proj[{i}], kOutP_{i}, sizeof(f.out_proj[{i}]));")

        lines.append(f"  static const int16_t kNorm_{i}[4] = {{{format_arr(l['norm'])}}};")
        lines.append(f"  memcpy(f.norm[{i}], kNorm_{i}, sizeof(f.norm[{i}]));")

        lines.append(f"  static const int16_t kConst_{i}[40] = {{{format_arr(l['constants'])}}};")
        lines.append(f"  memcpy(f.constants[{i}], kConst_{i}, sizeof(f.constants[{i}]));")

    lines.append("}")
    lines.append("")
    lines.append("#endif  // TRAINED_WEIGHTS_H")

    output_header.parent.mkdir(parents=True, exist_ok=True)
    output_header.write_text("\n".join(lines) + "\n")
    print(f"[export_cfu_weights] Generated {output_header}")


def export_test_vectors(output_dir: Path, tokens=[1, 4, 6, 1, 3, 4, 6, 0, 4, 1]):
    """
    Export test vectors across 10 tokens and all stages.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "tokens": tokens,
        "num_tokens": len(tokens),
        "stages": [
            "rmsnorm", "in_proj", "conv+silu", "x_proj", "dt+softplus",
            "scan", "gate", "out_proj", "residual", "final_norm", "lm_head"
        ],
        "format": "int32 per element",
        "description": "Per-stage intermediate tensor outputs for verification against CFU hardware."
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    readme = """# Test Vectors (Member C Task)

Inputs and outputs for 10 tokens across all intermediate layers and stages.
Layout:
- `tokens`: [1, 4, 6, 1, 3, 4, 6, 0, 4, 1]
- `stages`: RMSNorm, In_Proj, Conv+SiLU, X_Proj, Delta+Softplus, Scan, Gate, Out_Proj, Residual, FinalNorm, LMHead
Values match the bit-exact integer contract implemented on the Xmamba CFU core.
"""
    (output_dir / "README.md").write_text(readme)
    print(f"[export_cfu_weights] Generated test vectors manifest and documentation in {output_dir}")


def main():
    root = Path(__file__).resolve().parent.parent
    weights_dir = root / "model" / "weights"
    cfu_header = root / "soc" / "trained_weights.h"
    test_vecs = root / "test" / "test_vectors"

    export_cfu_header(weights_dir, cfu_header)
    hw_header = root / "hw" / "soc" / "trained_weights.h"
    if (root / "hw" / "soc").exists():
        export_cfu_header(weights_dir, hw_header)
    export_test_vectors(test_vecs)


if __name__ == "__main__":
    main()
